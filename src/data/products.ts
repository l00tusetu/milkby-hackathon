const l = (ru: string, en = '', be = '', zh = ''): LocalizedText => ({ ru, be, en, zh });

const parseWeightGrams = (label: string): number => {
  const m = label.replace(',', '.').match(/(\d+(?:\.\d+)?)\s*(кг|kg|л|l|гр?|g|мл|ml)?/i);
  if (!m) return 250;
  const num = parseFloat(m[1]);
  if (!Number.isFinite(num) || num <= 0) return 250;
  const unit = (m[2] || '').toLowerCase();
  if (unit === 'кг' || unit === 'kg' || unit === 'л' || unit === 'l') {
    return Math.round(num * 1000);
  }
  return Math.round(num);
};

let gtinCounter = 4810268001000;

interface CompactPkgInput {
  w: string;
  g?: number;
  s: string;
  t?: string;
  p: string;
  b?: number;
}

const pkg = (idPrefix: string, idx: number, item: CompactPkgInput): PackageVariant => {
  gtinCounter += 1;
  const storageText = item.t || '+2…+6 °C';
  return {
    id: `${idPrefix}-${idx + 1}`,
    weight: item.w,
    weightGrams: item.g ?? parseWeightGrams(item.w),
    shelfLife: l(item.s),
    storage: { ru: storageText, be: storageText, en: storageText, zh: storageText },
    packagingType: l(item.p),
    unitsPerBox: item.b ?? 12,
    gtin: String(gtinCounter),
  };
};

interface CompactProductInput {
  id: string;
  category: string;
  sub: string;
  name: string;
  desc: string;
  img: string;
  local: string;
  fat?: number;
  prot?: number;
  lf?: boolean;
  exp?: boolean;
  feat?: boolean;
  pkgs: CompactPkgInput[];
  chars: Record<string, string>;
  uses: string[];
  rel: string[];
}

const makeProduct = (input: CompactProductInput): Product => {
  const translations = productTranslations[input.id];
  if (!translations?.be || !translations.en || !translations.zh) {
    throw new Error(`Missing product card translations for "${input.id}"`);
  }

  const name: LocalizedText = {
    ru: input.name,
    be: translations.be.name,
    en: translations.en.name,
    zh: translations.zh.name,
  };
  const description: LocalizedText = {
    ru: input.desc,
    be: translations.be.description,
    en: translations.en.description,
    zh: translations.zh.description,
  };
  const characteristics: Record<string, LocalizedText> = {};
  for (const [k, v] of Object.entries(input.chars)) {
    characteristics[k] = l(v);
  }
  return {
    id: input.id,
    slug: input.id,
    category: input.category,
    subcategory: input.sub,
    name,
    description,
    image: `https://milk.by/upload/${input.img}`,
    localImage: `./images/${input.local}`,
    fatContent: input.fat,
    proteinContent: input.prot,
    lactoseFree: Boolean(input.lf),
    exportReady: Boolean(input.exp),
    featured: Boolean(input.feat),
    visible: true,
    packages: input.pkgs.map((item, idx) => pkg(input.id, idx, item)),
    characteristics,
    useCases: input.uses,
    relatedIds: input.rel,
    seo: {
      title: {
        ru: `${name.ru} — ОАО «Молочный Мир»`,
        be: `${name.be} — ААТ «Малочны Мір»`,
        en: `${name.en} — Molochny Mir`,
        zh: `${name.zh} — Molochny Mir`,
      },
      description: {
        ru: description.ru.split('\n')[0].slice(0, 160),
        be: description.be.split('\n')[0].slice(0, 160),
        en: description.en.split('\n')[0].slice(0, 160),
        zh: description.zh.split('\n')[0].slice(0, 160),
      },
      h1: name,
    },
  };
};

